#!/usr/bin/env python3
"""Generate unicode_ranges.h: the four character classes the qwen35 pre-tokenizer needs (\p{L}, \p{M},
\p{N}, \s), as sorted [lo,hi] range pairs, measured with the same `regex` module Strata splits with.

usage: gen_unicode.py [out.h]
"""
import json
import sys

import regex

CATS = {"L": r"\p{L}", "M": r"\p{M}", "N": r"\p{N}", "WS": r"\s"}


def ranges(pat: str) -> list[list[int]]:
    c = regex.compile(pat)
    rs: list[list[int]] = []
    for cp in range(0x110000):
        if c.match(chr(cp)):
            if rs and rs[-1][1] + 1 == cp:
                rs[-1][1] = cp
            else:
                rs.append([cp, cp])
    return rs


def main() -> int:
    out = sys.argv[1] if len(sys.argv) > 1 else "unicode_ranges.h"
    lines = ["// generated by gen_unicode.py from the regex module's Unicode tables (Python %s)" %
            sys.version.split()[0], "#ifndef UNICODE_RANGES_H", "#define UNICODE_RANGES_H",
            "#include <stdint.h>", ""]
    counts = {}
    for k, pat in CATS.items():
        rs = ranges(pat)
        counts[k] = len(rs)
        lines.append("static const uint32_t UR_%s[] = {" % k)
        for lo, hi in rs:
            lines.append("  %d, %d," % (lo, hi))
        lines.append("};")
        lines.append("#define UR_%s_N (%d)" % (k, len(rs)))
        lines.append("")
    lines.append("#endif")
    open(out, "w").write("\n".join(lines) + "\n")
    json.dump(counts, open(out + ".counts", "w"))
    print(" ".join("%s %d ranges" % (k, n) for k, n in counts.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
